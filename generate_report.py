import pandas as pd
import matplotlib.pyplot as plt
import seaborn as sns
from matplotlib.backends.backend_pdf import PdfPages
import textwrap

def generate_report():
    # Load data
    try:
        df = pd.read_csv('mid term grades.csv')
    except Exception as e:
        print(f"Error loading dataset: {e}")
        return

    sns.set_theme(style="whitegrid")
    
    report_filename = 'College_Analytics_Report.pdf'
    
    with PdfPages(report_filename) as pdf:
        
        # 1. Title Page
        fig, ax = plt.subplots(figsize=(8.5, 11))
        ax.axis('off')
        ax.text(0.5, 0.7, 'College Analytics Report\nMid-Term Grades Analysis', 
                size=26, ha='center', weight='bold', color='#1A252F')
        ax.text(0.5, 0.4, 'Automated Statistical Insights and Data Visualizations', 
                size=16, ha='center', color='#2C3E50')
        ax.text(0.5, 0.1, 'Generated by Statistical Explorer v1.0\n© 2026 Student Analytics System', 
                size=10, ha='center', color='gray')
        pdf.savefig(fig)
        plt.close()

        # 2. Histogram of Final Scores
        fig, (ax_text, ax_plot) = plt.subplots(2, 1, figsize=(8.5, 11), gridspec_kw={'height_ratios': [1, 2]})
        ax_text.axis('off')
        ax_text.text(0, 0.9, '1. Distribution of Final Scores', size=18, weight='bold', color='#2C3E50')
        explanation = ("This histogram illustrates the frequency distribution of final scores among students. "
                       "It helps identify the overall performance spread, indicating whether grades are "
                       "distributed normally or skewed toward specific ranges. The overlaid KDE (Kernel "
                       "Density Estimate) line provides a smooth representation of the data density, "
                       "highlighting the most common score ranges.")
        ax_text.text(0, 0.7, "\n".join(textwrap.wrap(explanation, 75)), size=12, va='top', color='#34495E')
        
        sns.histplot(data=df, x='final_score', bins=15, ax=ax_plot, kde=True, color="#2ECC71")
        ax_plot.set_title("Histogram: Final Score Distribution", size=14)
        ax_plot.set_xlabel("Final Score", size=12)
        ax_plot.set_ylabel("Frequency", size=12)
        pdf.savefig(fig)
        plt.close()

        # 3. Bar Plot: Pass Rate by Gender
        fig, (ax_text, ax_plot) = plt.subplots(2, 1, figsize=(8.5, 11), gridspec_kw={'height_ratios': [1, 2]})
        ax_text.axis('off')
        ax_text.text(0, 0.9, '2. Performance by Gender', size=18, weight='bold', color='#2C3E50')
        explanation = ("This bar chart compares the count of students who passed or failed, categorized by gender. "
                       "This visualization is crucial for identifying any gender-based performance trends or gaps. "
                       "By observing the ratio of 'Yes' to 'No' in the 'Passed' category for both genders, "
                       "educators can determine if specific demographics require additional academic support.")
        ax_text.text(0, 0.7, "\n".join(textwrap.wrap(explanation, 75)), size=12, va='top', color='#34495E')
        
        sns.countplot(data=df, x='gender', hue='passed', ax=ax_plot, palette="viridis")
        ax_plot.set_title("Bar Plot: Pass/Fail Status by Gender", size=14)
        ax_plot.set_xlabel("Gender", size=12)
        ax_plot.set_ylabel("Student Count", size=12)
        ax_plot.legend(title="Passed")
        pdf.savefig(fig)
        plt.close()

        # 4. Scatter Plot: Study Hours vs Final Score
        fig, (ax_text, ax_plot) = plt.subplots(2, 1, figsize=(8.5, 11), gridspec_kw={'height_ratios': [1, 2]})
        ax_text.axis('off')
        ax_text.text(0, 0.9, '3. Correlation: Study Effort vs. Results', size=18, weight='bold', color='#2C3E50')
        explanation = ("The scatter plot examines the relationship between weekly study hours and final exam scores. "
                       "A positive trend (upward slope) suggests that increased study time directly impacts "
                       "academic success. Points are color-coded by passing status, allowing for a clear "
                       "visualization of the effort-reward threshold for passing the course.")
        ax_text.text(0, 0.7, "\n".join(textwrap.wrap(explanation, 75)), size=12, va='top', color='#34495E')
        
        sns.scatterplot(data=df, x='study_hours_per_week', y='final_score', hue='passed', ax=ax_plot, palette="magma")
        ax_plot.set_title("Scatter Plot: Study Hours vs. Final Score", size=14)
        ax_plot.set_xlabel("Study Hours per Week", size=12)
        ax_plot.set_ylabel("Final Score", size=12)
        pdf.savefig(fig)
        plt.close()

        # 5. Box Plot: Scores by Parent Education
        fig, (ax_text, ax_plot) = plt.subplots(2, 1, figsize=(8.5, 11), gridspec_kw={'height_ratios': [1, 2]})
        ax_text.axis('off')
        ax_text.text(0, 0.9, '4. Impact of Socio-Economic Factors', size=18, weight='bold', color='#2C3E50')
        explanation = ("This box plot displays the distribution of final scores across different levels of parental "
                       "education. It provides insights into how a student's home environment might correlate "
                       "with academic outcomes. The box represents the interquartile range (IQR), while the "
                       "horizontal line within it marks the median score for each group.")
        ax_text.text(0, 0.7, "\n".join(textwrap.wrap(explanation, 75)), size=12, va='top', color='#34495E')
        
        sns.boxplot(data=df, x='parent_education', y='final_score', ax=ax_plot, palette="Set2")
        ax_plot.set_title("Box Plot: Score Distribution by Parent Education", size=14)
        ax_plot.set_xlabel("Parent Education Level", size=12)
        ax_plot.set_ylabel("Final Score", size=12)
        plt.setp(ax_plot.get_xticklabels(), rotation=30, ha='right')
        pdf.savefig(fig)
        plt.close()

        # 6. Pie Chart: Internet Access Accessibility
        fig, (ax_text, ax_plot) = plt.subplots(2, 1, figsize=(8.5, 11), gridspec_kw={'height_ratios': [1, 2]})
        ax_text.axis('off')
        ax_text.text(0, 0.9, '5. Resource Accessibility: Internet Access', size=18, weight='bold', color='#2C3E50')
        explanation = ("The pie chart represents the proportion of students who have access to the internet. "
                       "In modern education, internet access is a critical variable as it dictates a student's "
                       "ability to access online resources, research materials, and educational platforms. "
                       "This breakdown highlights the digital divide within the student population.")
        ax_text.text(0, 0.7, "\n".join(textwrap.wrap(explanation, 75)), size=12, va='top', color='#34495E')
        
        data = df['internet_access'].value_counts()
        ax_plot.pie(data, labels=data.index, autopct='%1.1f%%', startangle=140, 
                    colors=['#3498DB', '#E74C3C'], wedgeprops={'edgecolor': 'white'})
        ax_plot.set_title("Pie Chart: Internet Access Distribution", size=14)
        pdf.savefig(fig)
        plt.close()

        # 7. Statistical Summary Page
        fig, ax = plt.subplots(figsize=(8.5, 11))
        ax.axis('off')
        ax.text(0, 0.95, '6. Comprehensive Statistical Summary', size=18, weight='bold', color='#2C3E50')
        
        # Calculate summary stats
        num_cols = df.select_dtypes(include=['float64', 'int64']).columns
        summary_lines = ["NUMERIC PERFORMANCE METRICS:", ""]
        for col in num_cols:
            mean_val = df[col].mean()
            median_val = df[col].median()
            std_val = df[col].std()
            summary_lines.append(f"{col.upper()}:")
            summary_lines.append(f"  - Mean: {mean_val:.2f}")
            summary_lines.append(f"  - Median: {median_val:.2f}")
            summary_lines.append(f"  - Std Dev: {std_val:.2f}")
            summary_lines.append("")
            
        summary_lines.append("DEMOGRAPHIC MODES (MOST COMMON):")
        cat_cols = ['gender', 'parent_education', 'internet_access', 'passed']
        for col in cat_cols:
            if col in df.columns:
                mode_val = df[col].mode()[0]
                count = (df[col] == mode_val).sum()
                summary_lines.append(f"  - {col.title()}: {mode_val} (Freq: {count})")
        
        ax.text(0, 0.85, "\n".join(summary_lines), size=11, family='monospace', va='top', color='#2C3E50')
        
        explanation = ("This summary table provides a quantitative overview of the dataset. "
                       "Central tendency measures (Mean and Median) offer insights into average performance, "
                       "while Standard Deviation indicates the level of variability among students. "
                       "Demographic modes highlight the most common characteristics of the student body.")
        ax.text(0, 0.1, "\n".join(textwrap.wrap(explanation, 75)), size=10, style='italic', color='#7F8C8D')
        
        pdf.savefig(fig)
        plt.close()

    print(f"Report successfully generated: {report_filename}")

if __name__ == "__main__":
    generate_report()
